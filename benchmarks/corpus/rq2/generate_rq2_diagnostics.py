#!/usr/bin/env python3
"""Generate diagnostic tables for the frozen MLReproMutate RQ2 analysis.

This script does not modify classifications or empirical outcomes.

It reads the already outcome-joined case table generated by
generate_rq2_results.py and reports:

1. B02 operator × prospective oracle kind × outcome;
2. attrition/evaluability by workflow kind and prospective B02 oracle kind.
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path
from typing import Any


RQ2_DIR = Path(__file__).resolve().parent
RESULTS_DIR = RQ2_DIR / "results"

JOINED_PATH = RESULTS_DIR / "rq2_joined_cases.jsonl"

EXPECTED_TOTAL = 39
EXPECTED_MEANINGFUL = 23
EXPECTED_B02_MEANINGFUL = 15

OPERATORS = (
    "random-seed",
    "dependency-pin",
    "data-split",
    "cv-fold-count",
)

B02_ORACLES = (
    "assertion",
    "completion-only",
)

WORKFLOW_ORDER = (
    "upstream-test",
    "ci",
    "documented-validation",
    "documented-experiment",
    "documented-example",
)


class DiagnosticError(RuntimeError):
    """RQ2 diagnostic input is missing or inconsistent."""


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise DiagnosticError(
            f"cannot read {path}: {exc}"
        ) from exc

    rows: list[dict[str, Any]] = []

    for line_number, raw in enumerate(lines, start=1):
        if not raw.strip():
            continue

        try:
            value = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise DiagnosticError(
                f"{path}:{line_number}: invalid JSON: {exc}"
            ) from exc

        if not isinstance(value, dict):
            raise DiagnosticError(
                f"{path}:{line_number}: expected JSON object"
            )

        rows.append(value)

    return rows


def validate(rows: list[dict[str, Any]]) -> None:
    if len(rows) != EXPECTED_TOTAL:
        raise DiagnosticError(
            f"joined table has {len(rows)} rows; "
            f"expected {EXPECTED_TOTAL}"
        )

    ids = [row["case_id"] for row in rows]

    if len(set(ids)) != EXPECTED_TOTAL:
        raise DiagnosticError(
            "case_id values are not unique"
        )

    meaningful = [
        row
        for row in rows
        if row["meaningful_detection_denominator"]
    ]

    if len(meaningful) != EXPECTED_MEANINGFUL:
        raise DiagnosticError(
            f"meaningful denominator={len(meaningful)}; "
            f"expected {EXPECTED_MEANINGFUL}"
        )

    b02_meaningful = [
        row
        for row in meaningful
        if row["batch"] == "B02"
    ]

    if len(b02_meaningful) != EXPECTED_B02_MEANINGFUL:
        raise DiagnosticError(
            f"B02 meaningful denominator="
            f"{len(b02_meaningful)}; "
            f"expected {EXPECTED_B02_MEANINGFUL}"
        )


def pct(numerator: int, denominator: int) -> float | None:
    if denominator == 0:
        return None
    return 100.0 * numerator / denominator


def format_pct(value: float | None) -> str:
    if value is None:
        return "—"
    return f"{value:.1f}%"


def write_csv(
    path: Path,
    rows: list[dict[str, Any]],
) -> None:
    if not rows:
        raise DiagnosticError(
            f"refusing to write empty table: {path}"
        )

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=list(rows[0].keys()),
        )
        writer.writeheader()
        writer.writerows(rows)


def build_operator_oracle(
    rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """B02 meaningful cases by operator and prospective oracle."""

    meaningful_b02 = [
        row
        for row in rows
        if (
            row["batch"] == "B02"
            and row["meaningful_detection_denominator"]
        )
    ]

    table: list[dict[str, Any]] = []

    for operator in OPERATORS:
        for oracle in B02_ORACLES:
            subset = [
                row
                for row in meaningful_b02
                if (
                    row["operator"] == operator
                    and row["oracle_kind"] == oracle
                )
            ]

            counts = Counter(
                row["combined_outcome"]
                for row in subset
            )

            n = len(subset)
            killed = counts["killed"]
            survived = counts["survived"]

            table.append(
                {
                    "operator": operator,
                    "oracle_kind": oracle,
                    "meaningful_n": n,
                    "killed": killed,
                    "survived": survived,
                    "detection_percent": pct(
                        killed,
                        n,
                    ),
                }
            )

    return table


def category_row(
    *,
    dimension: str,
    scope: str,
    category: str,
    subset: list[dict[str, Any]],
) -> dict[str, Any]:
    selected = len(subset)

    evaluated = sum(
        bool(row["combined_evaluated"])
        for row in subset
    )

    meaningful_rows = [
        row
        for row in subset
        if row["meaningful_detection_denominator"]
    ]

    meaningful_n = len(meaningful_rows)

    counts = Counter(
        row["combined_outcome"]
        for row in meaningful_rows
    )

    return {
        "dimension": dimension,
        "scope": scope,
        "category": category,
        "selected": selected,
        "combined_evaluated": evaluated,
        "meaningful_n": meaningful_n,
        "evaluated_not_meaningful": (
            evaluated - meaningful_n
        ),
        "not_combined_evaluated": (
            selected - evaluated
        ),
        "meaningful_percent_of_selected": pct(
            meaningful_n,
            selected,
        ),
        "killed": counts["killed"],
        "survived": counts["survived"],
    }


def build_attrition(
    rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    table: list[dict[str, Any]] = []

    # Workflow-kind analysis uses the whole frozen 39-case frame.
    for workflow in WORKFLOW_ORDER:
        subset = [
            row
            for row in rows
            if row["workflow_kind"] == workflow
        ]

        table.append(
            category_row(
                dimension="workflow_kind",
                scope="B01+B02",
                category=workflow,
                subset=subset,
            )
        )

    # Oracle analysis is prospectively clean only for B02.
    b02 = [
        row
        for row in rows
        if row["batch"] == "B02"
    ]

    for oracle in B02_ORACLES:
        subset = [
            row
            for row in b02
            if row["oracle_kind"] == oracle
        ]

        table.append(
            category_row(
                dimension="oracle_kind",
                scope="B02-prospective",
                category=oracle,
                subset=subset,
            )
        )

    return table


def main() -> None:
    rows = read_jsonl(JOINED_PATH)
    validate(rows)

    operator_oracle = build_operator_oracle(
        rows
    )

    attrition = build_attrition(
        rows
    )

    write_csv(
        RESULTS_DIR
        / "rq2_b02_operator_oracle.csv",
        operator_oracle,
    )

    write_csv(
        RESULTS_DIR
        / "rq2_evaluability_by_category.csv",
        attrition,
    )

    print("RQ2 diagnostics: OK")

    print()
    print(
        "B02 meaningful operator × oracle:"
    )

    for row in operator_oracle:
        if row["meaningful_n"] == 0:
            continue

        print(
            f"  {row['operator']} × "
            f"{row['oracle_kind']}: "
            f"n={row['meaningful_n']}, "
            f"killed={row['killed']}, "
            f"survived={row['survived']}, "
            f"detection="
            f"{format_pct(row['detection_percent'])}"
        )

    print()
    print("Attrition/evaluability:")

    for row in attrition:
        print(
            f"  [{row['scope']}] "
            f"{row['dimension']}="
            f"{row['category']}: "
            f"selected={row['selected']}, "
            f"combined_evaluated="
            f"{row['combined_evaluated']}, "
            f"meaningful={row['meaningful_n']}, "
            f"meaningful/selected="
            f"{format_pct(
                row['meaningful_percent_of_selected']
            )}"
        )

    print()
    print(
        "outputs:"
    )
    print(
        "  "
        + str(
            RESULTS_DIR
            / "rq2_b02_operator_oracle.csv"
        )
    )
    print(
        "  "
        + str(
            RESULTS_DIR
            / "rq2_evaluability_by_category.csv"
        )
    )


if __name__ == "__main__":
    try:
        main()
    except DiagnosticError as exc:
        raise SystemExit(
            f"RQ2 diagnostics failed: {exc}"
        ) from exc